"""Write chip/uac_hc_fir.h: the fractional-delay filter of the USB audio input on the computer's clock
(chip/usb.c, FELUCCA_UAC_HOST_CLOCK).

A Kaiser-windowed sinc of N taps (cutoff FC of the rate, beta BETA) at P fractional positions t = p / P,
p = 0..P: tap j weighs the input frame at j - (N / 2 - 1) - t from the output. Rows P / 2 + 1 .. P are
rows P / 2 - 1 .. 0 backwards (the window and the sinc are even), so only rows 0..P / 2 are written. Each
row is rounded to Q30 and sums to exactly 1 << 30 (unity at DC). usb.c interpolates between two rows.

    python3 tools/uac_hc_fir.py > chip/uac_hc_fir.h
"""
import math

N, P, FC, BETA, Q = 16, 64, 0.46, 12.0, 30


def i0(x):
    s = t = 1.0
    for k in range(1, 40):
        t *= (x / (2.0 * k)) ** 2
        s += t
    return s


def row(p):
    t = p / P
    h = []
    for j in range(N):
        x = j - (N // 2 - 1) - t
        r = x / (N / 2.0)
        w = i0(BETA * math.sqrt(1.0 - r * r)) / i0(BETA) if abs(r) < 1.0 else 0.0
        s = 1.0 if x == 0 else math.sin(math.pi * 2.0 * FC * x) / (math.pi * 2.0 * FC * x)
        h.append(2.0 * FC * s * w)
    total = sum(h)
    q = [round(v / total * (1 << Q)) for v in h]
    q[max(range(N), key=lambda j: abs(q[j]))] += (1 << Q) - sum(q)   # the rounding's rest on the largest tap
    return q


def main():
    print("/* SPDX-License-Identifier: MPL-2.0\n * Copyright (C) 2026 henri (hdavid) */")
    print("/* Generated by tools/uac_hc_fir.py: do not edit. The USB audio input's fractional-delay filter on the")
    print(f" * computer's clock (usb.c, FELUCCA_UAC_HOST_CLOCK): a Kaiser-windowed sinc, {N} taps, cutoff {FC} of the")
    print(f" * rate, beta {BETA:g}, at t = p / {P}, rows 0..{P // 2} (row {P} - p is row p backwards), Q{Q}, each row")
    print(" * summing to exactly 1 << 30. */")
    print("#define UAC_HC_N %du" % N)
    print("#define UAC_HC_P %du" % P)
    print("#define UAC_HC_Q %d" % Q)
    print("static const int32_t UAC_HC[UAC_HC_P / 2u + 1u][UAC_HC_N] = {")
    for p in range(P // 2 + 1):
        print("    {" + ", ".join(str(v) for v in row(p)) + "},")
    print("};")


if __name__ == "__main__":
    main()
